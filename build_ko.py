#!/usr/bin/env python3
"""Generate the Korean page (ko/index.html) from index.html.

index.html is the single source. Every element that has a Korean version carries it in a
data-ko="..." attribute; this script swaps those in, rewrites the <head> SEO block, fixes
relative asset paths and points the language button back to the English page.

Run after editing index.html:   python3 build_ko.py
"""
import html
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent
BASE = "https://sjhan91.github.io/"

SEO_KO = f"""<!-- seo:start (generated by build_ko.py from index.html; do not edit ko/index.html by hand) -->
<title>한상준 (Sangjun Han) — AI Researcher, LG AI연구원</title>
<meta name="description" content="한상준 (Sangjun Han), LG AI연구원 Data Intelligence Lab AI Researcher. Time-series Foundation Model(EXAONE Forecast), 멀티모달 시계열 예측, 물리 시뮬레이터, 시계열 인과 추론, 음악 생성을 연구합니다.">
<meta name="author" content="한상준 (Sangjun Han)">
<link rel="canonical" href="{BASE}ko/">
<link rel="alternate" hreflang="en" href="{BASE}">
<link rel="alternate" hreflang="ko" href="{BASE}ko/">
<link rel="alternate" hreflang="x-default" href="{BASE}">
<meta property="og:type" content="profile">
<meta property="og:site_name" content="한상준 (Sangjun Han)">
<meta property="og:title" content="한상준 (Sangjun Han) — AI Researcher, LG AI연구원">
<meta property="og:description" content="Time-series Foundation Model(EXAONE Forecast), 시계열 예측, 인과 추론, 음악 생성 연구">
<meta property="og:url" content="{BASE}ko/">
<meta property="og:image" content="{BASE}sj.han.web.jpg">
<meta property="og:locale" content="ko_KR">
<meta property="og:locale:alternate" content="en_US">
<meta property="profile:first_name" content="Sangjun">
<meta property="profile:last_name" content="Han">
<meta name="twitter:card" content="summary">
<!-- seo:end -->"""

OPEN_TAG = re.compile(r'<([a-zA-Z][a-zA-Z0-9]*)\b[^>]*?\sdata-ko="([^"]*)"[^>]*>')


def matching_close(src, tag, start):
    """Index of the '</tag>' that closes the element whose content starts at `start`."""
    depth = 1
    pat = re.compile(r'<(/?)%s\b[^>]*>' % tag, re.I)
    for m in pat.finditer(src, start):
        if m.group(0).endswith('/>'):
            continue
        depth += -1 if m.group(1) else 1
        if depth == 0:
            return m.start()
    raise ValueError(f"unclosed <{tag}> at {start}")


def swap_korean(src):
    edits = []
    for m in OPEN_TAG.finditer(src):
        tag, ko = m.group(1), html.unescape(m.group(2))
        close = matching_close(src, tag, m.end())
        open_tag = m.group(0).replace(f' data-ko="{m.group(2)}"', '')
        edits.append((m.start(), close, open_tag + ko))
    for start, end, repl in sorted(edits, reverse=True):
        src = src[:start] + repl + src[end:]
    return src, len(edits)


def build():
    src = (ROOT / "index.html").read_text(encoding="utf-8")
    out, n = swap_korean(src)

    out = out.replace('<html lang="en">', '<html lang="ko">', 1)
    out = re.sub(r'<!-- seo:start.*?<!-- seo:end -->', lambda _: SEO_KO, out, count=1, flags=re.S)
    out = out.replace('src="sj.han.web.jpg"', 'src="../sj.han.web.jpg"')
    out = out.replace(
        '<a class="btn lang-switch" id="lang" href="ko/" hreflang="ko" lang="ko" aria-label="한국어 버전">',
        '<a class="btn lang-switch" id="lang" href="../" hreflang="en" lang="en" aria-label="English version">', 1)
    out = out.replace('<span id="lang-label">한국어</span>', '<span id="lang-label">English</span>', 1)
    assert 'data-ko=' not in out, "some data-ko attributes were not converted"

    dest = ROOT / "ko" / "index.html"
    dest.parent.mkdir(exist_ok=True)
    dest.write_text(out, encoding="utf-8")
    print(f"wrote {dest.relative_to(ROOT)}  ({n} Korean strings)")


if __name__ == "__main__":
    build()
